/* The wdbg spec of `mwtrace regalloc` (SPEC.md language), with {KEY} placeholders that mwt_build_expand fills from
 * the build's table (the RA_ keys of mwt_build.c). One log line per event; mwt_regalloc_parse.c lists the forms.
 * mwt_regalloc.c puts `only = "<name>"` in front of it: only the functions whose Object has that name are logged
 * (every function when it is ""). */
#include "mwt_regalloc.h"

const char *const MWT_REGALLOC_SPEC =
    "# mwtrace regalloc: the register allocator's decisions (generated; docs/compiler_regalloc.md)\n"
    "on = 0\n"
    "ic = 0\n"
    "\n"
    "# CodeGen_Generator: one function's code generation starts (its Object at argument +4)\n"
    "bp {RA_CODEGEN}\n"
    "    o = u32(u32(Esp + 4) + 4)\n"
    "    nm = cstr(rd(u32(o + 0xc) + 0xa, 255)) if o else \"\"\n"
    "    on = 1 if (only == \"\" or nm == only) else 0\n"
    "    out \"FN %#x %d %s\", o, on, nm\n"
    "end\n"
    "# CMangler_GetLinkName: an object's link name, the first time it is made\n"
    "bp {LN1}\n"
    "    out \"LN %#x %s\", Ebx, cstr(rd(Eax + 0xa, 300))\n"
    "end\n"
    "bp {LN2}\n"
    "    out \"LN %#x %s\", Ebx, cstr(rd(Eax + 0xa, 300))\n"
    "end\n"
    "# the inliner's argument binder (its callee at argument +0) and its renames of the callee's locals and parameter\n"
    "# objects to @NNN (the old name still at Object +0xc, the new one in Eax): logged for every function\n"
    "bp {RA_INL_BIND}\n"
    "    o = u32(Esp + 4)\n"
    "    out \"IB %#x %s\", o, cstr(rd(u32(o + 0xc) + 0xa, 255))\n"
    "end\n"
    "bp {RA_INL_BIND_RET}\n"
    "    out \"IBR\"\n"
    "end\n"
    "bp {RA_INL_LOCAL}\n"
    "    out \"INL l %s %s\", cstr(rd(Eax + 0xa, 255)), cstr(rd(u32(Esi + 0xc) + 0xa, 255))\n"
    "end\n"
    "bp {RA_INL_PARAM}\n"
    "    out \"INL p %s %s\", cstr(rd(Eax + 0xa, 255)), cstr(rd(u32(Edx + 0xc) + 0xa, 255))\n"
    "end\n"
    "\n"
    "# buildinterferencegraph: one class, one colouring attempt\n"
    "bp {RA_BUILD}\n"
    "    if on\n"
    "        c = u8({RA_G_CLASS})\n"
    "        out \"IG %d %d %d %d\", c, u32({RA_G_ITER}), u32({RA_G_NREAL} + 4 * c), u32({RA_G_USED} + 4 * c)\n"
    "    end\n"
    "end\n"
    "# coalescing: a copy's two roots merged (alias[hi] = lo), or refused\n"
    "bp {RA_CO_INTERF}\n"
    "    if on and Eax\n"
    "        out \"CX %d %d interferes\", Ebx & 0xffff, Ebp & 0xffff\n"
    "    end\n"
    "end\n"
    "bp {RA_CO_RESTR}\n"
    "    if on and Eax\n"
    "        out \"CX %d %d restriction\", Ebx & 0xffff, Ebp & 0xffff\n"
    "    end\n"
    "end\n"
    "bp {RA_CO_SET}\n"
    "    if on and Edi == u32(Edx + 4 * Ebx)\n"
    "        out \"CX %d %d set\", Eax & 0xffff, Edi\n"
    "    end\n"
    "end\n"
    "bp {RA_CO_MERGE}\n"
    "    if on\n"
    "        out \"CO %d %d\", Eax & 0xffff, Ebp & 0xffff\n"
    "    end\n"
    "end\n"
    "# the variables: parameters (arguments list) and locals (locals list), each with its VarInfo\n"
    "bp {RA_ARG}\n"
    "    if on\n"
    "        out \"ARG %#x %d %d %d %d %s\", Ebx, u8(Eax + 0xe), u8(Eax + 0xf), u16(Eax + 0x10), u16(Eax + 0x12), \\\n"
    "            cstr(rd(u32(Ebx + 0xc) + 0xa, 255))\n"
    "    end\n"
    "end\n"
    "bp {RA_LOC}\n"
    "    if on\n"
    "        out \"LOC %#x %d %d %d %d %s\", Ebx, u8(Eax + 0xe), u8(Eax + 0xf), u16(Eax + 0x10), u16(Eax + 0x12), \\\n"
    "            cstr(rd(u32(Ebx + 0xc) + 0xa, 255))\n"
    "    end\n"
    "end\n"
    "# a coalesced node's Object copied to its root (the root had none)\n"
    "bp {RA_INHERIT}\n"
    "    if on\n"
    "        out \"INH %d %#x\", Eax >> 5, Esi\n"
    "    end\n"
    "end\n"
    "# the rematerialisation walk: every instruction (counted) and every definition of a virtual register\n"
    "bp {RA_REMAT}\n"
    "    ic = 0\n"
    "end\n"
    "bp {RA_REMAT_INSN}\n"
    "    if on\n"
    "        ic += 1\n"
    "    end\n"
    "end\n"
    "bp {RA_REMAT_DEF}\n"
    "    if on\n"
    "        r = u16(Ebx + 4)\n"
    "        if r >= u32({RA_G_NREAL} + 4 * u8({RA_G_CLASS}))\n"
    "            out \"DEF %d %d %s\", r, ic, cstr(rd(u32({RA_OPNAMES} + 22 * u16(Ebp + 0x28)), 24))\n"
    "        end\n"
    "    end\n"
    "end\n"
    "# the complete graph: every virtual node (index, alias, flags, degree, colour, object, degree copy, remat)\n"
    "bp {RA_NODES}\n"
    "    if on\n"
    "        c = u8({RA_G_CLASS})\n"
    "        if Esi >= u32({RA_G_NREAL} + 4 * c)\n"
    "            out \"N %d %d %#x %d %d %#x %d %#x\", Esi, u16(u32({RA_G_ALIAS}) + 2 * Esi), u16(Ebx + 0x14), \\\n"
    "                u16(Ebx + 0x16), u16(Ebx + 0x12), u32(Ebx + 4), u16(Ebx + 0x18), u32(Ebx + 8)\n"
    "        end\n"
    "    end\n"
    "end\n"
    "\n"
    "# simplify: K, the sweeps, the pushes, the optimistic choice and its candidates\n"
    "bp {RA_SIMP_K}\n"
    "    if on\n"
    "        out \"K %d %d %d\", u8({RA_G_CLASS}), Eax, u8({RA_G_VLE})\n"
    "    end\n"
    "end\n"
    "bp {RA_SWEEP1}\n"
    "    if on\n"
    "        out \"SW\"\n"
    "    end\n"
    "end\n"
    "bp {RA_SWEEP2}\n"
    "    if on\n"
    "        out \"SW\"\n"
    "    end\n"
    "end\n"
    "bp {RA_PUSH_LOW}\n"
    "    if on\n"
    "        out \"P1 %d %d\", u16(Esi + 0x10), u16(Esi + 0x16)\n"
    "    end\n"
    "end\n"
    "bp {RA_EST}\n"
    "    if on\n"
    "        out \"EST\"\n"
    "    end\n"
    "end\n"
    "bp {RA_CAND1}\n"
    "    if on\n"
    "        out \"CAND %d %d %d %#x\", u16(Ebx + 0x10), u32(Ebx + 0xc), u16(Ebx + 0x16), u16(Ebx + 0x14)\n"
    "    end\n"
    "end\n"
    "bp {RA_CAND}\n"
    "    if on\n"
    "        out \"CAND %d %d %d %#x\", u16(Ecx + 0x10), u32(Ecx + 0xc), u16(Ecx + 0x16), u16(Ecx + 0x14)\n"
    "    end\n"
    "end\n"
    "bp {RA_PUSH_OPT}\n"
    "    if on\n"
    "        out \"OPT %d %d %d\", u16(Esi + 0x10), u32(Esi + 0xc), u16(Esi + 0x16)\n"
    "    end\n"
    "end\n"
    "bp {RA_PUSH_AFTER}\n"
    "    if on\n"
    "        out \"P2 %d %d\", u16(Edx + 0x10), u16(Edx + 0x16)\n"
    "    end\n"
    "end\n"
    "\n"
    "# select: the masks, each pop, its physical neighbours, the registers left free, the pick, a nonvolatile added\n"
    "bp {RA_SEL_VOL}\n"
    "    if on\n"
    "        out \"VOL %#x\", Eax\n"
    "    end\n"
    "end\n"
    "bp {RA_SEL_AVAIL}\n"
    "    if on\n"
    "        out \"AVAIL %#x\", Eax\n"
    "    end\n"
    "end\n"
    "bp {RA_SEL_NODE}\n"
    "    if on\n"
    "        out \"SEL %d %#x %d\", u16(Ebx + 0x10), u16(Ebx + 0x14), u32(Ebx + 0xc)\n"
    "    end\n"
    "end\n"
    "bp {RA_SEL_EDGE}\n"
    "    if on\n"
    "        if (Edi & 0xffff) < u32({RA_G_NREAL} + 4 * u8({RA_G_CLASS}))\n"
    "            out \"E %d %d\", u16(Ebx + 0x10), Edi & 0xffff\n"
    "        end\n"
    "    end\n"
    "end\n"
    "bp {RA_SEL_FREE}\n"
    "    if on\n"
    "        out \"FREE %#x\", Esi\n"
    "    end\n"
    "end\n"
    "bp {RA_SEL_PICK}\n"
    "    if on\n"
    "        out \"PICK %d\", Eax if Eax < 0x80000000 else -1\n"
    "    end\n"
    "end\n"
    "bp {RA_SEL_NV}\n"
    "    if on\n"
    "        out \"NV %d\", Eax & 0xffff if (Eax & 0xffff) != 0xffff else -1\n"
    "    end\n"
    "end\n"
    "bp {RA_SEL_SPILL}\n"
    "    if on\n"
    "        out \"SPILL %d\", u16(Ebx + 0x10)\n"
    "    end\n"
    "end\n"
    "bp {RA_SEL_RET}\n"
    "    if on\n"
    "        out \"SELR %d\", u32(Esp + 8)\n"
    "    end\n"
    "end\n"
    "# the operand rewrite after a colouring: a node whose Object's VarInfo gets the colour ([Object +0x40] +9 set)\n"
    "bp {RA_REWRITE_VAR}\n"
    "    if on\n"
    "        out \"RWV %d\", Edi\n"
    "    end\n"
    "end\n";
