/* The wdbg spec of `mwtrace sched` (SPEC.md language), with {KEY} placeholders that mwt_build_expand fills from the
 * build's table (the SC_ keys of mwt_build.c, and the RA_ and LN keys it shares with regalloc). One log line per
 * event; mwt_sched_parse.c lists the forms. mwt_sched.c puts `only = "<name>"` in front of it: only the functions
 * whose Object has that name are logged (every function when it is ""). Node, edge and block pointers are the
 * compiler's own (the scheduler's nodes live in a heap freed after each block, so they repeat across blocks); pcode
 * pointers are stable for the whole function. */
#include "mwt_sched.h"

const char *const MWT_SCHED_SPEC =
    "# mwtrace sched: the instruction scheduler's decisions (generated; docs/compiler_regalloc.md)\n"
    "on = 0\n"
    "\n"
    "# CodeGen_Generator: one function's code generation starts (its Object at argument +4)\n"
    "bp {RA_CODEGEN}\n"
    "    o = u32(u32(Esp + 4) + 4)\n"
    "    nm = cstr(rd(u32(o + 0xc) + 0xa, 255)) if o else \"\"\n"
    "    on = 1 if (only == \"\" or nm == only) else 0\n"
    "    out \"FN %#x %d %s\", o, on, nm\n"
    "end\n"
    "# CMangler_GetLinkName: an object's link name, the first time it is made\n"
    "bp {LN1}\n"
    "    out \"LN %#x %s\", Ebx, cstr(rd(Eax + 0xa, 300))\n"
    "end\n"
    "bp {LN2}\n"
    "    out \"LN %#x %s\", Ebx, cstr(rd(Eax + 0xa, 300))\n"
    "end\n"
    "\n"
    "# scheduleinstructions: one pass (its argument: 0 before register allocation, 1 after), the machine model\n"
    "bp {SC_DRIVER}\n"
    "    if on\n"
    "        out \"SD %d %d %d %d %d %d 0 0 0\", u8(Esp + 4), u32({SC_G_COLORING}), u8({SC_G_MODE}), \\\n"
    "            u8({SC_G_PROC}), u8({G_X112}), u8({SC_G_PRE})\n"
    "    end\n"
    "end\n"
    "# the driver's visit of each block: scheduled when it has more than 2 instructions (and, in pass 1, flags & 3 clear)\n"
    "bp {SC_VISIT}\n"
    "    if on\n"
    "        out \"BV %#x %d %#x %d\", Ebx, u16(Ebx + 0x28), u16(Ebx + 0x2a), u32(Ebx + 0x1c)\n"
    "    end\n"
    "end\n"
    "# the block scheduler: one block (its first instruction at +0x14, its count at +0x28) and the machine model the\n"
    "# driver picked (+0 issue width, +4, +8; at the driver's entry the pointer still holds the previous pass's model)\n"
    "bp {SC_BLOCK}\n"
    "    if on\n"
    "        b = u32(Esp + 4)\n"
    "        m = u32({SC_G_MACHINE})\n"
    "        out \"SB %#x %d %d %#x %#x %d %d %d\", b, u32(b + 0x1c), u16(b + 0x28), u16(b + 0x2a), u32(b + 0x14), \\\n"
    "            u32(m), u32(m + 4), u32(m + 8)\n"
    "    end\n"
    "end\n"
    "# a node made (the block is walked from its last instruction): node, pcode, opcode, latency, pcode flags, priority\n"
    "bp {SC_NODE}\n"
    "    if on\n"
    "        op = u16(Esi + 0x28)\n"
    "        out \"NC %#x %#x %s %d %#x %#x %d\", Ebx, Esi, cstr(rd(u32({RA_OPNAMES} + 22 * op), 24)), u16(Ebx + 0x10), \\\n"
    "            u32(Esi + 0xc), u32(Esi + 0x10), u8({SC_PRIO} + 22 * op)\n"
    "    end\n"
    "end\n"
    "# a register operand the dependence builder looks at: class, register, effect (1 use, 2 def)\n"
    "bp {SC_OPND}\n"
    "    if on\n"
    "        out \"OP %d %d %d\", u8(Ebx + 1), u16(Ebx + 4), u16(Ebx + 2)\n"
    "    end\n"
    "end\n"
    "# the edge adder: from (the new node, earlier in the block) to (a later node), latency flag, the call site\n"
    "bp {SC_EDGE}\n"
    "    if on\n"
    "        out \"EA %#x %#x %d %#x\", u32(Esp + 4), u32(Esp + 8), u8(Esp + 12), u32(Esp)\n"
    "    end\n"
    "end\n"
    "bp {SC_EDGE_NEW}\n"
    "    if on\n"
    "        out \"EN %d\", Edi & 0xffff\n"
    "    end\n"
    "end\n"
    "bp {SC_EDGE_UPD}\n"
    "    if on\n"
    "        out \"EU %d\", Edi & 0xffff\n"
    "    end\n"
    "end\n"
    "# memory: may_alias's answer for (new node, later node), and the precheck's (nonzero: no dependence, not asked)\n"
    "bp {SC_ALIAS_LS}\n"
    "    if on\n"
    "        out \"MA ls %#x %#x %d\", Esi, u32(Ebx + 4), Eax & 0xff\n"
    "    end\n"
    "end\n"
    "bp {SC_ALIAS_SL}\n"
    "    if on\n"
    "        out \"MA sl %#x %#x %d\", Ebx, u32(Esi + 4), Eax & 0xff\n"
    "    end\n"
    "end\n"
    "bp {SC_ALIAS_SS}\n"
    "    if on\n"
    "        out \"MA ss %#x %#x %d\", Ebx, u32(Esi + 4), Eax & 0xff\n"
    "    end\n"
    "end\n"
    "bp {SC_PRE_LS}\n"
    "    if on\n"
    "        out \"MP ls %#x %#x %d\", Esi, u32(Ebx + 4), Eax & 0xff\n"
    "    end\n"
    "end\n"
    "bp {SC_PRE_SL}\n"
    "    if on\n"
    "        out \"MP sl %#x %#x %d\", Ebx, u32(Esi + 4), Eax & 0xff\n"
    "    end\n"
    "end\n"
    "bp {SC_PRE_SS}\n"
    "    if on\n"
    "        out \"MP ss %#x %#x %d\", Ebx, u32(Esi + 4), Eax & 0xff\n"
    "    end\n"
    "end\n"
    "# the complete nodes in program order: height, slack (greatest height - height), predecessors, the greatest height\n"
    "bp {SC_SLACK}\n"
    "    if on\n"
    "        out \"N %#x %d %d %d %d\", Edx, u16(Edx + 0x16), u16(Edx + 0x14), u16(Edx + 0x18), u16({SC_G_MAXH})\n"
    "    end\n"
    "end\n"
    "# list scheduling: a selection (cycle, issue slot), its can-issue answers, incumbent, successor counts, takes\n"
    "bp {SC_SELECT}\n"
    "    if on\n"
    "        out \"S %d %d\", u16(Esp), u32(Esp + 4)\n"
    "    end\n"
    "end\n"
    "bp {SC_CI1}\n"
    "    if on\n"
    "        out \"CI %#x %d\", Edi, Eax\n"
    "    end\n"
    "end\n"
    "bp {SC_INC}\n"
    "    if on\n"
    "        out \"INC %#x\", Edi\n"
    "    end\n"
    "end\n"
    "bp {SC_CI2}\n"
    "    if on\n"
    "        out \"CI %#x %d\", Esi, Eax\n"
    "    end\n"
    "end\n"
    "bp {SC_SUCC}\n"
    "    if on\n"
    "        out \"SC %#x %#x %d %d\", Esi, Edi, Ecx, Ebp\n"
    "    end\n"
    "end\n"
    "bp {SC_TAKE}\n"
    "    if on\n"
    "        out \"T %#x\", Esi\n"
    "    end\n"
    "end\n"
    "# a node issued, each successor's remaining predecessors and earliest cycle, the end of a cycle and of the block\n"
    "bp {SC_ISSUE}\n"
    "    if on\n"
    "        out \"I %#x\", Esi\n"
    "    end\n"
    "end\n"
    "bp {SC_UPD}\n"
    "    if on\n"
    "        out \"U %#x %d %d %d\", Edx, u16(Edx + 0x18), Edi, u16(Edx + 0x12)\n"
    "    end\n"
    "end\n"
    "bp {SC_CYCLE}\n"
    "    if on\n"
    "        out \"CY %d\", u16(Esp)\n"
    "    end\n"
    "end\n"
    "bp {SC_END}\n"
    "    if on\n"
    "        out \"BE\"\n"
    "    end\n"
    "end\n"
    "\n"
    "# the register allocator's rematerialisation walk (regalloc's instruction numbers: blocks forward, each block from\n"
    "# its last instruction): its start and every instruction\n"
    "bp {RA_REMAT}\n"
    "    if on\n"
    "        out \"RW\"\n"
    "    end\n"
    "end\n"
    "bp {RA_REMAT_INSN}\n"
    "    if on\n"
    "        out \"RI %#x\", Ebp\n"
    "    end\n"
    "end\n"
    "# assemblefunction: every instruction emitted, in the object's order (pcode, opcode, block)\n"
    "bp {SC_ASM}\n"
    "    if on\n"
    "        out \"AS %#x %s %#x\", Esi, cstr(rd(u32({RA_OPNAMES} + 22 * u16(Esi + 0x28)), 24)), u32(Esi + 8)\n"
    "    end\n"
    "end\n";
