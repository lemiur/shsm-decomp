/* The wdbg spec of `mwtrace inline` (SPEC.md language), with {KEY} placeholders that mwt_build_expand fills from the
 * build's table. One log line per event; mwt_inline.c parses them (the line forms are listed there). */
#include "mwt_inline.h"

const char *const MWT_INLINE_SPEC =
    "# mwtrace inline: the inliner's decisions (generated; docs/compiler_inline.md)\n"
    "lastfp = 0\n"
    "curdef = 0\n"
    "inci = 0\n"
    "\n"
    "# CInline_CheckInlineability(Object *func, Statement **stmts, Boolean *out): once per defined function\n"
    "bp {CHECKINL}\n"
    "    o = u32(Esp + 4)\n"
    "    curdef = o\n"
    "    out \"DEF %#x %#x %d %d %s\", o, u32(o + 0x14), u8({G_AUTOINLINE}), u8({G_DONTINLINE}), cstr(rd(u32(o + 0xc) + 0xa, 255))\n"
    "end\n"
    "bp {CHECKINL_RESULT}\n"
    "    out \"DEFR %#x %d %#x\", Ebp, Ebx & 0xff, u32(u32(Ebp + 0x10) + 0x1a)\n"
    "end\n"
    "bp {CHECKINL_QUAL4}\n"
    "    out \"DEFR %#x 0 %#x qual4\", Ebp, u32(u32(Ebp + 0x10) + 0x1a)\n"
    "end\n"
    "bp {AUTO_FAILCOUNT}\n"
    "    out \"AUTO %#x fail-count %d %d\", u32(Esp + 0xc), Ebp, u32({G_MAXAUTO})\n"
    "end\n"
    "bp {AUTO_FAILLOCALS}\n"
    "    out \"AUTO %#x fail-locals %d %d\", u32(Esp + 0xc), Ebp, Eax\n"
    "end\n"
    "bp {AUTO_OK}\n"
    "    out \"AUTO %#x ok %d %d\", u32(Esp + 0xc), Ebp, Eax\n"
    "end\n"
    "# its tree walk over a candidate's body (CExpr_IRTreeWalk's callback): every call node (kind 0x39) and its callee\n"
    "bp {BODYWALK}\n"
    "    n = u32(Esp + 4)\n"
    "    if u8(n) == 0x39\n"
    "        fr = u32(n + 0x10)\n"
    "        if u8(fr) == 0x3b\n"
    "            o = u32(fr + 0x10)\n"
    "            if u8(o + 2) == {C_DALIAS}\n"
    "                o = u32(o + 0x40)\n"
    "            end\n"
    "            out \"BODY %#x %#x %d %#x %s\", curdef, o, u8(o + 2), u32(fr + 8), cstr(rd(u32(o + 0xc) + 0xa, 255))\n"
    "        else\n"
    "            out \"BODY %#x 0 0 0 (indirect)\", curdef\n"
    "        end\n"
    "    end\n"
    "end\n"
    "\n"
    "# the inlinability classifier: 0 not inlinable, 3 inlined as statements, 6 inlined as an expression\n"
    "bp {KIND_NEVERINLINE}\n"
    "    out \"KIND %#x 0 never-inline\", Ebp\n"
    "end\n"
    "bp {KIND_RESULTDTOR}\n"
    "    out \"KIND %#x 0 result-class-destructor\", Ebp\n"
    "end\n"
    "bp {KIND_VARARGS}\n"
    "    out \"KIND %#x 0 varargs\", Ebp\n"
    "end\n"
    "bp {KIND_DOBJSTACK}\n"
    "    out \"KIND %#x 3 destructor-objects\", Ebp\n"
    "end\n"
    "bp {KIND_END}\n"
    "    out \"KIND %#x %d body\", Ebp, Eax & 0xff\n"
    "end\n"
    "bp {KIND_RESULTCLASS}\n"
    "    out \"KIND %#x 0 result-class\", Ebp\n"
    "end\n"
    "bp {KIND_PARAMDTOR}\n"
    "    out \"KIND %#x 0 parameter-destructor\", Ebp\n"
    "end\n"
    "bp {KIND_EXPR3E}\n"
    "    out \"KIND %#x 0 expression-0x3e\", Ebp\n"
    "end\n"
    "\n"
    "# the pass driver: one caller's inlining starts\n"
    "bp {EXPSTMTS}\n"
    "    out \"CUR %#x %d %d %d %d %d %d %d\", u32(Esp + 4), u8({G_AUTOINLINE}), u32({G_MAXAUTO}), u16({G_DEPTH}), \\\n"
    "        u8({G_BOTTOMUP}), u8({G_ALWAYS}), u8({G_DONTINLINE}), u8({G_X112})\n"
    "end\n"
    "bp {STMT1}\n"
    "    fp = u32(Edi + 0x16)\n"
    "    if fp != lastfp\n"
    "        lastfp = fp\n"
    "        out \"FILE %#x %s\", fp, cstr(rd(u32(fp) + 0xa, 300)) if fp else \"\"\n"
    "    end\n"
    "    out \"STMT %#x %d %#x\", Edi, u32(Edi + 0x1a), fp\n"
    "end\n"
    "bp {STMT2}\n"
    "    fp = u32(Edi + 0x16)\n"
    "    if fp != lastfp\n"
    "        lastfp = fp\n"
    "        out \"FILE %#x %s\", fp, cstr(rd(u32(fp) + 0xa, 300)) if fp else \"\"\n"
    "    end\n"
    "    out \"STMT %#x %d %#x\", Edi, u32(Edi + 0x1a), fp\n"
    "end\n"
    "\n"
    "# the decision for one call node\n"
    "bp {DECIDE}\n"
    "    e = u32(Esp + 8)\n"
    "    fr = u32(e + 0x10)\n"
    "    o = u32(fr + 0x10)\n"
    "    if u8(o + 2) == {C_DALIAS}\n"
    "        o = u32(o + 0x40)\n"
    "    end\n"
    "    out \"CHK %#x %#x %#x %d %#x %d %#x %#x %s\", e, u32({G_CURFN}), o, u16({G_LEVEL}), u32(o + 0x14), u8(o + 2), \\\n"
    "        u32(u32(o + 0x10) + 0x1a), u32(fr + 8), cstr(rd(u32(o + 0xc) + 0xa, 255))\n"
    "end\n"
    "bp {DECIDE_FD}\n"
    "    if Eax\n"
    "        out \"FD %d %d\", u32(Eax + 8), u8(Eax + {C_FD_KIND})\n"
    "    end\n"
    "end\n"
    "bp {R_NOTCAND}\n"
    "    out \"R not-candidate\"\n"
    "end\n"
    "bp {R_NOFUNCDATA}\n"
    "    out \"R no-funcdata\"\n"
    "end\n"
    "bp {R_ALWAYS}\n"
    "    out \"R always-inline\"\n"
    "end\n"
    "bp {R_BULAST}\n"
    "    out \"R bottom-up-last\"\n"
    "end\n"
    "bp {R_BUSIZE}\n"
    "    out \"R bottom-up-size\"\n"
    "end\n"
    "bp {BU_CMP}\n"
    "    out \"BU %d %d\", Eax, u32({G_MAXSIZE})\n"
    "end\n"
    "bp {R_LVL3}\n"
    "    out \"R level3-cost\"\n"
    "end\n"
    "bp {R_LVL1}\n"
    "    out \"R level1-cost\"\n"
    "end\n"
    "bp {R_LVL2}\n"
    "    out \"R level2-cost\"\n"
    "end\n"
    "bp {R_PASS}\n"
    "    out \"R pass\"\n"
    "end\n"
    "bp {R_OPTFIT}\n"
    "    out \"R opt-fit\"\n"
    "end\n"
    "bp {R_ANALYSIS}\n"
    "    out \"R ipa-analysis %d\", Eax & 0xff\n"
    "end\n"
    "bp {R_NOCUR}\n"
    "    out \"R no-current-function\"\n"
    "end\n"
    "bp {R_NOCURFD}\n"
    "    out \"R no-caller-funcdata\"\n"
    "end\n"
    "\n"
    "# after the expansion call: inlined in place (1) or not (0); the statement-inline queue; a queued expansion\n"
    "bp {XP}\n"
    "    out \"XP %#x %d\", Esi, u8(Esp + 3)\n"
    "end\n"
    "bp {QUEUE}\n"
    "    out \"Q %#x %d\", u32(Esp + 0x5c), u16({G_QUEUE})\n"
    "end\n"
    "bp {XS}\n"
    "    out \"XS %#x\", Ebx\n"
    "end\n"
    "\n"
    "# CMangler_GetLinkName: an object's link name, the first time it is made\n"
    "bp {LN1}\n"
    "    out \"LN %#x %s\", Ebx, cstr(rd(Eax + 0xa, 300))\n"
    "end\n"
    "bp {LN2}\n"
    "    out \"LN %#x %s\", Ebx, cstr(rd(Eax + 0xa, 300))\n"
    "end\n"
    "\n"
    "# CInline_ComputeInlineability over a function's IR (at its definition, and after its inlining): its cost walk\n"
    "# meets every call node (the cost function of node kind 0x39)\n"
    "bp {COMPUTE}\n"
    "    inci = 1\n"
    "    out \"CI %#x\", u32(u32(Esp + 4) + 4)\n"
    "end\n"
    "bp {COMPUTE_RET}\n"
    "    inci = 0\n"
    "    out \"CIE\"\n"
    "end\n"
    "bp {CALLCOST}\n"
    "    if inci\n"
    "        fr = u32(u32(Esp + 4) + 0x10)\n"
    "        if u8(fr) == 0x3b\n"
    "            o = u32(fr + 0x10)\n"
    "            if u8(o + 2) == {C_DALIAS}\n"
    "                o = u32(o + 0x40)\n"
    "            end\n"
    "            out \"FC %#x %d %#x %s\", o, u8(o + 2), u32(fr + 8), cstr(rd(u32(o + 0xc) + 0xa, 255))\n"
    "        else\n"
    "            out \"FC 0 0 0 (indirect)\"\n"
    "        end\n"
    "    end\n"
    "end\n"
    "\n"
    "# the call-graph visitor after a caller's inlining: the growth test undoes it, or the new IR is kept\n"
    "bp {REVERT}\n"
    "    out \"REVERT %#x %d %d\", u32(Esp + 4), Ebx, Edx\n"
    "end\n"
    "bp {KEEP}\n"
    "    out \"KEEP %#x\", u32(Esp + 4)\n"
    "end\n"
    "bp {EXPAND}\n"
    "    out \"EXPAND\"\n"
    "end\n";
